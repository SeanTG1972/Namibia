"""Regenerate rates.json (and docs/rates.js for the web page) from the print-ready rates workbook.

Usage:
    python extract_rates.py path/to/Sandfontein-Rates-print-ready.xlsx

Reads the per-guest columns ("Actual cost paid by each guest", columns H and I)
from the direct rate tabs (USD, NAD, EUR, GBP), so the calculator always matches
the published sheets. The calculator is for bookings made directly with
Sandfontein, so agent and STO rates are deliberately left out: this repo is public.
"""
import json
import re
import sys
from pathlib import Path

import openpyxl

FIRST_ROW = 14  # row holding the 1st guest
MAX_GUESTS = 18


def extract(xlsx_path):
    wb = openpyxl.load_workbook(xlsx_path, data_only=True)
    workings = wb["Workings (Internal Use Only)"]
    year = workings["B2"].value
    long_stay_discount = workings["B5"].value  # "Discount for 5+ night stays"
    cards = {}
    for ws in wb.worksheets:
        channel, currency = ws["H7"].value, ws["I7"].value
        if channel != "DIRECT":  # never export agent or STO rates
            continue
        high, low = [], []
        for row in range(FIRST_ROW, FIRST_ROW + MAX_GUESTS):
            high.append(round(float(ws.cell(row, 8).value), 2))
            low.append(round(float(ws.cell(row, 9).value), 2))
        name = re.sub(r"\s*\(", " (", ws.title)  # "DirectRates(GBP)" -> "DirectRates (GBP)"
        cards[name] = {
            "channel": channel.title(),
            "currency": currency,
            "high": high,
            "low": low,
        }
    return {
        "year": year,
        "source": Path(xlsx_path).name,
        "high_season_months": [4, 5, 6, 7, 8, 9, 10],  # Apr-Oct; Nov-Mar is low season
        "child_discount": 0.5,
        "long_stay_nights": 5,
        "long_stay_discount": long_stay_discount,
        "repeat_guest_discount": 0.1,  # added together with the long-stay discount
        "max_guests": MAX_GUESTS,
        "rate_cards": cards,
    }


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = extract(sys.argv[1])
    out = Path(__file__).with_name("rates.json")
    out.write_text(json.dumps(data, indent=2) + "\n")
    # Same data for the GitHub Pages calculator in docs/
    web = Path(__file__).resolve().parent.parent / "docs" / "rates.js"
    web.write_text("// Generated by rate-calculator/extract_rates.py. Do not edit by hand.\n"
                   f"window.SANDFONTEIN_RATES = {json.dumps(data, indent=2)};\n")
    print(f"Wrote {len(data['rate_cards'])} direct rate cards for {data['year']} to {out} and {web}")
